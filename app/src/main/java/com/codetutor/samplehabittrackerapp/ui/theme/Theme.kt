/**
 * The app theme. Dynamic colour is deliberately not used: the brand green stays consistent on every
 * device (design decision, DESIGN.md).
 */
@Composable
fun SampleHabitTrackerAppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColorScheme else LightColorScheme,
        typography = Typography,
        content = content,
    )
}
